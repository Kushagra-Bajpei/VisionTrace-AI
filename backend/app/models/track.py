"""
Track model representing continuous ByteTrack object tracks across frames within a video.
"""
import uuid
from typing import TYPE_CHECKING, Any, Dict, List, Optional
from sqlalchemy import Float, ForeignKey, Integer, String, Uuid
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base
from app.models.base import JSONType, TimestampMixin, UUIDMixin

if TYPE_CHECKING:
    from app.models.video import Video
    from app.models.event import Event


class Track(Base, UUIDMixin, TimestampMixin):
    """
    Continuous object track across video frames generated by ByteTrack.
    Track IDs are video-scoped.
    """
    __tablename__ = "tracks"

    video_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("videos.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    track_id: Mapped[int] = mapped_column(Integer, nullable=False, index=True)
    object_class: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    start_time: Mapped[float] = mapped_column(Float, nullable=False)
    end_time: Mapped[float] = mapped_column(Float, nullable=False)
    start_frame: Mapped[int] = mapped_column(Integer, nullable=False)
    end_frame: Mapped[int] = mapped_column(Integer, nullable=False)
    confidence_avg: Mapped[float] = mapped_column(Float, nullable=False)
    attributes: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSONType, nullable=True)

    # Relationships
    video: Mapped["Video"] = relationship("Video", back_populates="tracks")
    events: Mapped[List["Event"]] = relationship("Event", back_populates="track")

    def __repr__(self) -> str:
        return f"<Track {self.track_id} ({self.object_class}) in Video {self.video_id}>"
